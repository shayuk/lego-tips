// Helper functions for building AI prompts

/** Build textual context lines based on course details */
export const buildCourseContext = (
  courseName?: string,
  faculty?: string,
  department?: string
): string => {
  if (courseName && faculty && department) {
    return `שם הקורס: "${courseName}"
       פקולטה: "${faculty}"
       מחלקה: "${department}"`;
  }
  return '';
};

/** Wrap course description as a syllabus block */
export const formatSyllabusData = (courseDescription: string): string => {
  return `
    תכני הקורס המפורטים:
    "${courseDescription}"
  `;
};

interface InstructionParams {
  selectedComponents: string[];
  hasMinimalContent: boolean;
  hasPlaceholderContent: boolean;
  courseName?: string;
  faculty?: string;
  department?: string;
}

/**
 * Generate the instructions section of the prompt, including
 * special handling when course content is missing.
 */
export const generateInstructionsPrompt = ({
  selectedComponents,
  hasMinimalContent,
  hasPlaceholderContent,
  courseName,
  faculty,
  department
}: InstructionParams): string => {
  const specificContentInstructions = `
    2. **בחר נושא ספציפי אחד וממוקד** מתוך תכני הקורס שסופקו. 
       - **דוגמה:** אם בתכנים מוזכר "תיאוריות למידה של פבלוב וסקינר", המשימה חייבת להתמקד בתיאוריות אלה, ולא ב"תיאוריות למידה" באופן כללי.
       - **התעלם מהוראות קודמות לבחור "נושא אחד או יותר"**. עליך לבחור נושא ספציפי אחד כדי ליצור מטלה ממוקדת.`;

  const researchContentInstructions = `
    **הוראות מיוחדות - תוכן הקורס חסר או מינימלי:**
    מכיוון שהמרצה לא סיפק תוכן מפורט, תפקידך כעת הוא לפעול כחוקר פדגוגי ובונה תכניות לימודים.

    1. **בצע סימולציה של מחקר:** חפש (בידע הפנימי שלך) סילבוס של קורס דומה באוניברסיטה ישראלית (למשל, אוניברסיטת אריאל, אוניברסיטת תל אביב).
       - **דוגמה לתהליך החשיבה שלך:** "המרצה ביקש קורס 'מדעי המדינה לתואר ראשון' באוניברסיטת אריאל. אני אמצא נושאים נפוצים בקורס כזה, למשל 'דמוקרטיה וחירות'. אני אבחר סוגיה ספציפית מתוך זה, כמו 'המתח בין ביטחון לזכויות אדם בדמוקרטיות מערביות'."
    
    2. **בחר נושא ספציפי וממוקד אחד** מתוך הסילבוס שמצאת. אל תבחר נושא כללי.
       - **דוגמה טובה:** "תיאוריית ההתקשרות של בולבי" (עבור קורס מבוא לפסיכולוגיה).
       - **דוגמה גרועה:** "נושאים בפסיכולוגיה".

    3. **הוסף למטלה בסיס תיאורטי עשיר:** גם אם הנושא כללי, עליך להציע מסגרת תיאורטית לניתוח.
      - **דוגמה למטלה עשירה בנושא 'אישיות והפרעותיה':**
        "### הרחבה תיאורטית לתמיכה במטלה:
        לצורך ביצוע המטלה ברמה מעמיקה, יש לשלב לפחות אחת מהתיאוריות הבאות:
        - **לניתוח נרקיסיזם:** ניתן להיעזר בפסיכולוגיית העצמי של קוהוט, בתיאוריה של קרנברג, או בקריטריונים של DSM-5.
        - **לניתוח אישיות גבולית:** מומלץ לשלב את המודל הביו-חברתי של לינהאן, תיאוריית ההתקשרות של בולבי, או מודל הסכמות של יאנג.
        השימוש בתיאוריה נדרש ליישום פרשני מעמיק על המקרה, לא רק לתיאור."

    4. **ציין בתחילת המטלה** על מה התבססת: "מכיוון שלא סופק תוכן ספציפי, המטלה מתבססת על נושא הליבה 'X' הנפוץ בקורסים דומים."`;
  
  const handleLecturerInstructions = `
    - **אם המרצה כתב:** "המטלה תתרכז בהיסטוריה של הסכסוך הערבי-ישראלי במאה ה-20" **והעלה גם סילבוס** - המטלה חייבת להתמקד בנושא שהמרצה ביקש, ולהשתמש במושגים הרלוונטיים מהסילבוס.
    - **אם יש רק טקסט חופשי ללא סילבוס** - השתמש בו כמקור עיקרי לתכנים ולהוראות.
    - **אם יש רק סילבוס ללא הוראות ספציפיות** - בחר נושא ספציפי אחד מתוך הסילבוס בהתאם לרמת הקורס.`;

  return `
    הרכיבים הפדגוגיים שנבחרו: [${selectedComponents.join(', ')}]

    **הוראות חובה:**

    1. **נתח בקפידה את כל תכני הקורס** שסופקו לעיל.
       ${handleLecturerInstructions}

    ${hasMinimalContent || hasPlaceholderContent ? researchContentInstructions : specificContentInstructions}

    3. **הרחב את הטיפים הפדגוגיים:** אם התיאור של טיפ פדגוגי הוא כללי (למשל, "עבודה קבוצתית"), באחריותך להרחיב אותו עם פרטי יישום קונקרטיים ומקצועיים, כאילו היית יועץ פדגוגי מומחה.
  `;
};

/** General static instructions for the AI's "personality" and core rules */
export const buildSystemPrompt = (): string => `
    **תפקיד וזהות:** אתה מומחה פדגוגי ובונה תכניות לימודים באקדמיה הישראלית. אתה מיומן ביצירת מטלות ספציפיות, ממוקדות ומעוררות מחשבה.

    **המשימה המרכזית שלך:** ליצור מטלה אקדמית מלאה, כולל הוראות מפורטות, בסיס תיאורטי עשיר, ומחוון הערכה מקצועי.

    **כלל הזהב (חובה ליישום): לעולם אל תיצור מטלה גנרית.** כל מטלה חייבת להיות סביב נושא, תיאוריה או סוגיה ספציפית שמתאימה לקורס. אם המידע שסופק אינו מספיק, חקור (באמצעות הידע הפנימי שלך) ומצא נושא מתאים ושלב בו מסגרת תיאורטית מוצקה.
    
    **הוראת-על (Highest Priority):** אם סופק תוכן קורס מפורט (סילבוס, מאמר, וכו'), הוא המקור היחיד והמחייב ליצירת המטלה. **אסור לך להשתמש בידע חיצוני או להמציא נושאים** אם התוכן שסופק מאפשר בחירת נושא מתוכו. התייחס לתוכן שסופק כ"מקור האמת" הבלעדי.

    **כללים קריטיים שאסור לעבור עליהם (כישלון בביצועם יפסול את התוצאה):**
    - **התבסס תמיד על תכנים ספציפיים:** אם סופק תוכן, השתמש בו. אם לא, מצא תוכן ספציפי בעצמך. לעולם אל תמציא דוגמאות כלליות.
    - **ודא התאמה אקדמית:** המטלה חייבת להיות תואמת לשם הקורס, לפקולטה ולמחלקה. אל תיצור מטלה בפסיכולוגיה לקורס בהיסטוריה.
    - **העדף הוראות מרצה:** אם המרצה סיפק הוראות בטקסט חופשי, הן גוברות על כל תוכן אחר.
    - **היה ברור ומדיד:** כל הוראה לסטודנט חייבת להיות ברורה, ספציפית וניתנת למדידה.
    - **שלב את כל הרכיבים:** כל רכיב פדגוגי שנבחר חייב להיות משולב במטלה באופן עמוק ומשמעותי, לא שטחי.
    - **מחוון מפורט:** המחוון חייב לכלול קריטריונים ברורים, תיאורים לכל רמת ביצוע, ומשקלים באחוזים.
`;
