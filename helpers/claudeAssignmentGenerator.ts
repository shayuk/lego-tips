// Use import.meta.env for environment variables (type declarations should be in vite-env.d.ts)
const CLAUDE_API_KEY = import.meta.env.VITE_CLAUDE_API_KEY;
const OPENAI_API_KEY = import.meta.env.VITE_OPENAI_API_KEY;
const OPENAI_MODEL = import.meta.env.VITE_OPENAI_MODEL || "gpt-4o";

export async function generateIntegratedAssignment({
  courseName,
  faculty,
  department,
  courseDescription,
  selectedPedagogicalComponents
}: {
  courseName?: string,
  faculty?: string,
  department?: string,
  courseDescription: string,
  selectedPedagogicalComponents: string[]
}): Promise<{ html: string; modelUsed: string }> {
  const courseContext = courseName && faculty && department 
    ? `שם הקורס: "${courseName}"
       פקולטה: "${faculty}"
       מחלקה: "${department}"`
    : '';

  // Validate that we have some course information
  if (!courseDescription || courseDescription.trim().length < 5) {
    throw new Error("Course information is missing. Please provide at least basic course information.");
  }

  const prompt = `
    ${courseContext}
    
    תכני הקורס המפורטים: 
    "${courseDescription}"
    
    **הוראות לניתוח התוכן:**
    - אם רואה קטע "--- תוכן הסילבוס ---" - החלק לפני הקטע הוא הוראות ספציפיות מהמרצה, והחלק אחרי הוא תכנים אקדמיים
    - אם אין הפרדה כזו - כל התוכן הוא מקור אחד (או סילבוס או הוראות)
    - **תן עדיפות להוראות הספציפיות של המרצה** על פני בחירה אקראית מתוך הסילבוס
    
    הרכיבים הפדגוגיים שנבחרו: [${selectedPedagogicalComponents.join(", ")}]

    **הוראות חובה:**
    
    1. **נתח בקפידה את כל תכני הקורס** שסופקו לעיל. 
       - אם יש קטע של "תוכן הסילבוס" - התייחס אליו כמקור עיקרי לתכנים האקדמיים
       - אם יש טקסט נוסף לפני או אחרי הסילבוס - התייחס אליו כהוראות ספציפיות מהמרצה
       - שלב בין שני המקורות: השתמש בתכנים האקדמיים מהסילבוס והתמקד בנושאים הספציפיים שהמרצה ביקש
       - זהה נושאים ספציפיים, תיאוריות, חוקרים, ומושגים המוזכרים בכל החלקים
    
    2. **אם התכנים מפורטים:** בחר נושא ספציפי אחד או יותר מתוך תכני הקורס שסופקו (לדוגמה: תיאוריות למידה של פבלוב וסקינר, גישות תיאורטיות בפסיכולוגיה, שיטות מחקר, פסיכולוגיה ביולוגית, וכו').
    
    **אם התכנים כלליים או לא מפורטים:** השתמש בידע שלך על הקורס הספציפי (בהתבסס על שם הקורס, פקולטה ומחלקה) ובחר נושא או תיאוריה ספציפית שמתאימה לרמת הקורס ולמוסד האקדמי. לדוגמה:
    - עבור "מבוא לפסיכולוגיה" תואר ראשון: בחר תיאוריה ספציפית כמו תיאוריית ההתקשרות של בולבי, תיאוריות למידה של פבלוב או סקינר, או גישת הפסיכואנליזה של פרויד.
    - עבור קורסים מתקדמים: בחר תיאוריות או מחקרים עכשוויים ברמה מתאימה.
    
    3. **צור משימה שמתמקדת בנושאים הספציפיים** שזיהית או בחרת, ולא בנושאים כלליים או דמיוניים.
    
    4. **השתמש במושגים, תיאוריות וחוקרים** שמוזכרים בתכני הקורס, או אם התכנים כלליים - במושגים מתאימים לרמת הקורס (לדוגמה: פבלוב, סקינר, פרויד, בולבי, גישות פסיכואנליטית/התנהגותית/קוגניטיבית).
    
    5. **שלב את כל הרכיבים הפדגוגיים שנבחרו באופן ספציפי ומשמעותי:**
    
    **חובה לשלב כל אחד מהרכיבים הבאים במטלה:** ${selectedPedagogicalComponents.join(", ")}
    
         **הנחיות לשילוב רכיבים פדגוגיים:**
     - אם נבחר "עבודה בקבוצות" - חייב לכלול:
       * הוראות ספציפיות לעבודה בקבוצות (מספר סטודנטים בקבוצה, איך נוצרות הקבוצות)
       * חלוקת תפקידים ספציפיים לכל חבר בקבוצה (מי אחראי על מה)
       * דרישות להצגה או מצגת בכיתה
       * הסבר על איך הקבוצות יעבדו יחד ויתאמו
       * דרישות לתיעוד עבודת הקבוצה (יומן עבודה, תיאום וכו')
               * הוראות לפתרון קונפליקטים בקבוצה
        * הסבר על איך ייעשה הציון (קבוצתי/אישי/משולב)
        * ציר זמן ולוח זמנים לעבודה בקבוצות (מתי להיפגש, מתי לסיים כל שלב)
        * הוראות לניהול הזמן ופגישות הקבוצה
    - אם נבחר "אירוע אקטואלי" - חייב לכלול הוראות ספציפיות לבחירת וניתוח אירוע אקטואלי רלוונטי
    - אם נבחר "ניתוח פרומפטים" או "שימוש ב-AI" - חייב לכלול הוראות לעבודה עם כלי AI וניתוח הפרומפטים
    - אם נבחר "הערכת עמיתים" - חייב לכלול הוראות להערכת עמיתים עם מחוונים ספציפיים
    - אם נבחר "רפלקציה" - חייב לכלול דרישה לרפלקציה אישית מובנית
    - אם נבחר "מחקר פעולה" - חייב לכלול הוראות לביצוע מחקר פעולה בשלבים
    - אם נבחר "פורטפוליו" - חייב לכלול הוראות לבניית פורטפוליו עם רכיבים שונים
    - אם נבחר "מיפוי מושגים" - חייב לכלול הוראות ליצירת מיפוי מושגים ויזואלי
    - אם נבחר "מקרה בוחן" - חייב לכלול הוראות לניתוח מקרה בוחן ספציפי
    - אם נבחר "סימולציה" - חייב לכלול הוראות להשתתפות או עיצוב סימולציה
    
    **אסור לך לדלג על רכיבים או לשלב אותם בצורה כללית - כל רכיב חייב להיות מובנה בפירוט במטלה.**
    
    **כלול בהכרח בהוראות המשימה:**
    - דרישות אורך: מינימום 800 מילים (או התאם לעבודה בקבוצות)
    - פורמט הגשה: קובץ Word (.docx) או מצגת PowerPoint (אם נדרשת הצגה)
    - צירוף צילום מסך של ההתכתבות עם כלי AI (אם רלוונטי למשימה)
    - תאריך הגשה ודרישות טכניות נוספות
    - אם עבודה בקבוצות: הוסף דרישות ספציפיות להגשה קבוצתית (רשימת חברי הקבוצה, יומן עבודה, חלוקת תפקידים, וכו')
    
    6. **כתוב מחוון מפורט** (טבלה) שכולל קריטריונים ספציפיים לכל אחד מהרכיבים הפדגוגיים שנבחרו:
    
    **קריטריונים בסיסיים (חובה לכלול תמיד):**
       - הבנת התיאוריה/נושא (0-7 בסיסי, 8-15 מתקדם, 16-20 מיטבי)
       - יישום המושגים (0-7 בסיסי, 8-15 מתקדם, 16-20 מיטבי)  
       - ביטוי שפתי ומבנה (0-7 בסיסי, 8-15 מתקדם, 16-20 מיטבי)
       - מקורות ואמינות (0-7 בסיסי, 8-15 מתקדם, 16-20 מיטבי)
    
    **קריטריונים ספציפיים לכל רכיב פדגוגי שנבחר (חובה לכלול):**
       - אם נבחר "עבודה בקבוצות" - קריטריון "עבודת צוות ושיתוף פעולה"
       - אם נבחר "אירוע אקטואלי" - קריטריון "ניתוח אירוע אקטואלי"
       - אם נבחר "ניתוח פרומפטים" או "שימוש ב-AI" - קריטריון "שימוש ב-AI וניתוח פרומפטים"
       - אם נבחר "הערכת עמיתים" - קריטריון "איכות הערכת עמיתים"
       - אם נבחר "רפלקציה" - קריטריון "רפלקציה אישית ומטא-קוגניציה"
       - אם נבחר "מחקר פעולה" - קריטריון "ביצוע מחקר פעולה"
       - אם נבחר "פורטפוליו" - קריטריון "איכות הפורטפוליו וארגון"
       - אם נבחר "מיפוי מושגים" - קריטריון "מיפוי מושגים ויזואלי"
       - אם נבחר "מקרה בוחן" - קריטריון "ניתוח מקרה בוחן"
       - אם נבחר "סימולציה" - קריטריון "השתתפות/עיצוב סימולציה"
    
    **כל קריטריון חייב לכלול תיאור מפורט לכל רמה (בסיסי, מתקדם, מיטבי) ומשקל אחוזי.**
    
    7. **התחל את התשובה** בציון הנושאים הספציפיים שזיהית מתכני הקורס או בחרת מהידע שלך, והסבר את הבחירה שלך.
       - אם המרצה כתב הוראות ספציפיות (לדוגמה: "המטלה תתרכז בהיסטוריה של הסכסוך הערבי-ישראלי במאה ה-20") - חייב להתמקד בדיוק בנושא הזה
       - אם יש גם סילבוס - השתמש בו כמקור לתיאוריות ומושגים הרלוונטיים לנושא שהמרצה ביקש
    
    8. **הפלט בעברית בפורמט HTML נקי וארגון מסודר** ללא תגי HTML מיותרים בתחילה או בסוף. התחל ישירות עם תוכן המשימה והסתיים עם סיום המחוון.
    
    9. **מבנה הפלט הנדרש - פורמט מסודר ואקדמי:**
       
       **חלק א: כותרת המסמך והקדמה**
       - התחל עם כותרת ברורה של המסמך בתוך <h1>
       - כלול פרטי הקורס (שם הקורס, קוד קורס, מרצה, וכו') בתוך <div class="course-info">
       - קו הפרדה
       
       **חלק ב: מטרת המשימה**
       - כותרת משנה: "מטרת המשימה" בתוך <h2>
       - הסבר קצר על מטרת המשימה
       - קו הפרדה
       
               **חלק ג: תיאור המשימה והוראות**
        - כותרת משנה: "תיאור המשימה והוראות" בתוך <h2>
        - הסבר מפורט על המשימה
        - הסבר מפורט על איך כל הרכיבים הפדגוגיים שנבחרו משתלבים יחד במשימה
        - רשימה מסודרת של הוראות עם מספרים לכל רכיב פדגוגי
        - קו הפרדה
       
       **חלק ד: דרישות הגשה**
       - כותרת משנה: "דרישות הגשה" בתוך <h2>
       - רשימה מסודרת של דרישות טכניות
       - קו הפרדה
       
       **חלק ה: מחוון הערכה**
       - כותרת משנה: "מחוון הערכה" בתוך <h2>
       - טבלה מפורטת עם עיצוב נקי
    
    **אסור לך:**
    - להשתמש בדוגמאות דמיוניות או כלליות
    - ליצור משימות שאינן מתאימות לרמת הקורס או לתחום הלימוד
    - להתעלם מהתכנים הספציפיים שסופקו (אם הם מפורטים)
    - לבחור נושאים שאינם מתאימים לקורס הספציפי (אם התכנים כלליים)
    
    **דוגמאות למה שאני מצפה:** 
    - אם בתכני הקורס מוזכרים "תיאוריות למידה של פבלוב וסקינר", המשימה צריכה להתמקד בתיאוריות האלה.
    - אם הקורס הוא "מבוא לפסיכולוגיה" ללא תכנים מפורטים, בחר תיאוריה ספציפית כמו "תיאוריית ההתקשרות של בולבי" והתמקד בה.
    - אם הקורס הוא "פסיכולוגיה קוגניטיבית מתקדמת", בחר תיאוריות עכשוויות ברמה מתאימה.
    - **אם המרצה כתב:** "המטלה תתרכז בהיסטוריה של הסכסוך הערבי-ישראלי במאה ה-20" **והעלה גם סילבוס** - חייב להתמקד בנושא הזה ולהשתמש בתיאוריות ובמושגים מהסילבוס הרלוונטיים לנושא הספציפי הזה.
    - **אם יש רק טקסט חופשי ללא סילבוס** - השתמש בו כמקור עיקרי לתכנים והוראות.
    - **אם יש רק סילבוס ללא הוראות ספציפיות** - בחר נושא מתוך הסילבוס בהתאם לרמת הקורס.
    
    **דוגמה למבנה HTML הרצוי:**
    <h1>מסמך מטלה לקורס: [שם הקורס]</h1>
    <div class="course-info">
        <p><strong>שם הקורס:</strong> [שם הקורס]</p>
        <p><strong>קוד קורס:</strong> [קוד]</p>
        <p><strong>מרצה:</strong> [שם המרצה]</p>
    </div>
    <hr>
    <h2>מטרת המשימה</h2>
    <p>[תיאור המטרה]</p>
    <hr>
    <h2>תיאור המשימה והוראות</h2>
    <p>[תיאור המשימה]</p>
    <ol>
        <li>[הוראה 1]</li>
        <li>[הוראה 2]</li>
    </ol>
    <hr>
    <h2>דרישות הגשה</h2>
    <ul>
        <li>[דרישה 1]</li>
        <li>[דרישה 2]</li>
    </ul>
    <hr>
    <h2>מחוון הערכה</h2>
    <table border="1" style="width: 100%; border-collapse: collapse;">
        <tr>
            <th style="padding: 8px; background-color: #f5f5f5;">קריטריון</th>
            <th style="padding: 8px; background-color: #f5f5f5;">ביצוע בסיסי (0-7 נקודות)</th>
            <th style="padding: 8px; background-color: #f5f5f5;">ביצוע מתקדם (8-15 נקודות)</th>
            <th style="padding: 8px; background-color: #f5f5f5;">ביצוע מיטבי (16-20 נקודות)</th>
        </tr>
        <tr>
            <td style="padding: 8px;">[קריטריון 1]</td>
            <td style="padding: 8px;">[תיאור בסיסי]</td>
            <td style="padding: 8px;">[תיאור מתקדם]</td>
            <td style="padding: 8px;">[תיאור מיטבי]</td>
                 </tr>
     </table>
     
     **דוגמאות לשילוב רכיבים פדגוגיים:**
     - עבודה בקבוצות + אירוע אקטואלי + ניתוח פרומפטים: "כל קבוצה תחלק את העבודה: חלק מהחברים יבחרו ויממפו תיאוריה רלוונטית מהקורס, חלק אחר יבחרו וינתחו אירוע אקטואלי באמצעות התיאוריה, וחלק שלישי יבצעו ניתוח באמצעות כלי AI. כל הקבוצה תשלב את החלקים למצגת או דוח מוגמר להצגה."
     - עבודה בקבוצות + הערכת עמיתים: "כל קבוצה תציג את עבודתها, והסטודנטים יעריכו את עבודות הקבוצות האחרות לפי מחוון שיסופק."
     - רפלקציה + מחקר פעולה: "הסטודנטים יבצעו מחקר פעולה קטן וירשמו רפלקציה על התהליך, הלמידה והתובנות."
  `;

  // Debug: log the prompt to console
  console.log("AI Prompt being sent:", prompt);

  // Try Claude first
  if (CLAUDE_API_KEY) {
    try {
      const response = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "x-api-key": CLAUDE_API_KEY,
          "anthropic-version": "2023-06-01",
          "content-type": "application/json"
        },
        body: JSON.stringify({
          model: "claude-3-sonnet-20240229",
          max_tokens: 4000,
          messages: [
            { role: "user", content: prompt }
          ]
        })
      });
      if (response.ok) {
        const data = await response.json();
        if (data.content?.[0]?.text) {
          return { html: data.content[0].text, modelUsed: "Claude 3 Sonnet" };
        }
      } else {
        console.warn("Claude API error:", response.status, response.statusText);
      }
    } catch (err) {
      console.warn("Claude API call failed, falling back to OpenAI:", err);
    }
  }

  // Fallback to OpenAI GPT-4o
  if (OPENAI_API_KEY) {
    try {
      const response = await fetch("https://api.openai.com/v1/chat/completions", {
        method: "POST",
        headers: {
          "Authorization": `Bearer ${OPENAI_API_KEY}`,
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          model: OPENAI_MODEL,
          max_tokens: 4000,
          messages: [
            { role: "user", content: prompt }
          ]
        })
      });
      if (response.ok) {
        const data = await response.json();
        if (data.choices?.[0]?.message?.content) {
          return { html: data.choices[0].message.content, modelUsed: OPENAI_MODEL };
        }
      } else {
        throw new Error("OpenAI API error: " + response.statusText);
      }
    } catch (err) {
      console.error("OpenAI API call failed:", err);
      throw err;
    }
  }

  throw new Error("No valid API key for Claude or OpenAI, or both APIs failed.");
} 